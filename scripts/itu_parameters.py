"""Draft ITU NGSO filing parameter sheet for FORGE STAR, generated from the design in this repo.

Pulls the constellation (Stage 3 design, sim/equatorial_study.py), radio links (forgestar/params/rf.yaml),
gateways and the Resolution 35 milestone rule into one sheet that spectrum counsel can turn into the
ICASA/ITU submission (API / coordination request, Appendix 4 data). Writes docs/itu/FILING_PARAMETERS.md.

Everything here is a draft for counsel: band choices, emission designators and PFD limits must be
confirmed against the Radio Regulations (Art. 5, 9, 11, 21, 22; Appendix 4) and ICASA's band plan.
Usage: python3 scripts/itu_parameters.py [--filing-date 2027-10-01] [--filed-sats 96]
"""
from __future__ import annotations

import argparse
import datetime as dt
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from forgestar.linkbudget import LINKS, fspl_db, slant_range_km  # noqa: E402

SHELLS = [  # name, sats, planes, inclination, altitude km  (Stage 3 design + growth room in the filing)
    ("A (main)", 42, 7, 45.0, 550.0),
    ("B (equatorial)", 6, 1, 10.0, 550.0),
]
GATEWAYS = [("Hartebeesthoek", "ZA", -25.89, 27.69), ("Cape Town", "ZA", -33.93, 18.42),
            ("Walvis Bay", "NA", -22.95, 14.50), ("Mauritius", "MU", -20.20, 57.50),
            ("Malindi", "KE", -3.00, 40.20), ("Lagos", "NG", 6.50, 3.40)]
BANDS = [  # link key, service, direction, band (MHz), emission designator (draft), note
    ("nbiot_uplink", "MSS (Earth-to-space)", "device → satellite", "1980–2010", "3K75G7W", "3GPP n256; NB-IoT single-tone"),
    ("nbiot_downlink", "MSS (space-to-Earth)", "satellite → device", "2170–2200", "180KG7W", "3GPP n256; NB-IoT carrier"),
    ("ais_rx", "Maritime mobile-satellite (Earth-to-space), receive only", "ship → satellite", "161.9625–161.9875, 162.0125–162.0375", "16K0GXW", "AIS 1/2 (RR Appendix 18); satellite receives only"),
    ("feeder_downlink", "EESS/SRS-style feeder (space-to-Earth)", "satellite → gateway", "8025–8400", "10M0G1D", "BPSK, RS + conv. coded store-and-forward downlink"),
]


def pfd_dbw_m2(eirp_dbw: float, range_km: float) -> float:
    return eirp_dbw - 10 * math.log10(4 * math.pi * (range_km * 1e3) ** 2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--filing-date", default="2027-10-01", help="date the filing is received by the ITU (assumed)")
    ap.add_argument("--filed-sats", type=int, default=96, help="satellites in the filing (design 48 + growth)")
    a = ap.parse_args()
    filed = dt.date.fromisoformat(a.filing_date)
    biu = filed.replace(year=filed.year + 7)

    L = ["# Draft ITU NGSO filing parameters — FORGE STAR", "",
         "Generated by `scripts/itu_parameters.py` from the repo's design. **Draft for spectrum counsel**: "
         "bands, emission designators and limits must be confirmed against the Radio Regulations and ICASA's band plan "
         "before submission.", "",
         "## Administration and system", "",
         "| Item | Value |", "|---|---|",
         "| Notifying administration | South Africa (ICASA) |",
         "| System type | Non-geostationary (NGSO), store-and-forward IoT, AIS reception, sovereign data relay |",
         f"| Satellites in the filing | {a.filed_sats} (Stage 3 design: {sum(s[1] for s in SHELLS)}; the rest is growth room) |",
         f"| Filing received (assumed) | {filed.isoformat()} |",
         f"| Bring-into-use deadline (7 years) | {biu.isoformat()} |", "",
         "## Orbital shells (circular)", "",
         "| Shell | Satellites (design) | Planes | Inclination | Altitude | Apogee/perigee | Period |", "|---|---|---|---|---|---|---|"]
    for name, n, p, inc, alt in SHELLS:
        period = 2 * math.pi * math.sqrt((6378.137 + alt) ** 3 / 398600.4418) / 60
        L.append(f"| {name} | {n} | {p} | {inc:.0f}° | {alt:.0f} km | {alt:.0f} / {alt:.0f} km | {period:.1f} min |")
    L += ["", "## Frequency assignments (draft)", "",
          "| Link | Service | Direction | Band (MHz) | Emission | Max EIRP | Max PFD at surface | Note |",
          "|---|---|---|---|---|---|---|---|"]
    for key, svc, direction, band, emission, note in BANDS:
        l = LINKS[key]
        if l.sat_side == "tx":
            eirp = l.tx_power_dbw + l.tx_gain_dbi
            worst = max(pfd_dbw_m2(eirp - l.sat_gain_loss_db(e), slant_range_km(e)) for e in range(5, 91))
            bw_4k = 10 * math.log10(min(l.bandwidth_hz, 4000) / l.bandwidth_hz)
            pfd = f"{worst:.1f} dB(W/m²) ({worst + bw_4k:.1f} in 4 kHz)"
            eirp_s = f"{eirp:.1f} dBW"
        else:
            eirp_s, pfd = f"{l.tx_power_dbw + l.tx_gain_dbi:.1f} dBW (earth station)", "— (satellite receives)"
        L.append(f"| {l.name} | {svc} | {direction} | {band} | {emission} | {eirp_s} | {pfd} | {note} |")
    L += ["", "PFD: worst case over elevations 5–90° from `forgestar/linkbudget.py` (satellite antenna pattern included). "
          "Counsel to compare with RR Article 21 limits and Appendix 5 coordination thresholds for each band.", "",
          "## Earth stations (gateways)", "", "| Gateway | Country | Latitude | Longitude | Role |", "|---|---|---|---|---|"]
    for name, cc, la, lo in GATEWAYS:
        role = "owned (SA)" if cc == "ZA" else "partner / leased; data relayed to SA"
        L.append(f"| {name} | {cc} | {la:.2f} | {lo:.2f} | {role} |")
    L += ["", "## Deployment milestones (Resolution 35, draft)", "",
          "| Milestone | Deadline | Satellites needed | Planned |", "|---|---|---|---|"]
    for pct, yrs in [(10, 2), (50, 5), (100, 7)]:
        need = math.ceil(a.filed_sats * pct / 100) if pct < 100 else a.filed_sats - 1
        L.append(f"| M{['10','50','100'].index(str(pct))+1} ({pct}%) | {biu.replace(year=biu.year + yrs).isoformat()} | {need} | "
                 + ("Stage 2 (6–12 sats) covers it" if pct == 10 else "Stage 3 (48) + growth" if pct == 50 else "Requires the growth satellites or a reduced filing") + " |")
    L += ["", "100% may be the filed number minus one (Res. 35). Missing M1 caps the filing at 10× the satellites deployed; "
          "missing M2 at 2×. If growth past 48 is uncertain, file closer to the design number.", "",
          "## Open items for counsel", "",
          "- Confirm n256 MSS band availability in SA and coordination with terrestrial IMT/MSS incumbents.",
          "- Confirm the feeder band (X-band 8025–8400 MHz vs Ka) and gateway licensing in NA, MU, KE, NG.",
          "- AIS reception: confirm satellite AIS (receive-only) treatment under Appendix 18 / Res. 360.",
          "- Decide the filed satellite count (design 48 vs growth to ~96) against milestone risk."]
    out = ROOT / "docs" / "itu" / "FILING_PARAMETERS.md"; out.parent.mkdir(exist_ok=True); out.write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
