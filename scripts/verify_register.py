"""Build docs/verification/VERIFY.md: everything that still needs confirming before external use.

Collects:
  1. claims in docs/verification/register.yaml (regulatory, market, commercial, ownership)
  2. every radio parameter in forgestar/params/rf.yaml that is not datasheet/measured
  3. items flagged reverify in readiness/readiness.yaml
  4. model assumption groups in model/assumptions.yaml (all illustrative until replaced)
Usage: python3 scripts/verify_register.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from forgestar.linkbudget import param_status  # noqa: E402

DONE = {"counsel-confirmed", "quoted", "measured", "datasheet"}


def main():
    reg = yaml.safe_load((ROOT / "docs/verification/register.yaml").read_text())
    rf = param_status()
    rd = yaml.safe_load((ROOT / "readiness/readiness.yaml").read_text())
    model = yaml.safe_load((ROOT / "model/assumptions.yaml").read_text())

    open_claims = [c for c in reg["claims"] if c["status"] not in DONE]
    open_rf = [r for r in rf if r[3] not in DONE]
    L = ["# Verification register", "",
         f"Generated by `scripts/verify_register.py`. Claims last web-checked {reg['checked_on']}. "
         "Nothing here is legal or financial advice.", "",
         "| Area | Open | Total |", "|---|---|---|",
         f"| Claims (regulatory, market, commercial, ownership) | {len(open_claims)} | {len(reg['claims'])} |",
         f"| Radio parameters (`forgestar/params/rf.yaml`) | {len(open_rf)} | {len(rf)} |",
         f"| Readiness items needing counsel | {sum(1 for i in rd['items'] if i.get('reverify'))} | {len(rd['items'])} |",
         f"| Financial model assumption groups | {len(model) - 1} | {len(model) - 1} |", "",
         "## Claims", "", "| # | Claim | Status | Confirm by | Finding |", "|---|---|---|---|---|"]
    for c in reg["claims"]:
        L.append(f"| {c['id']} | {c['claim']} | {c['status']} | {c['confirm_by']} | {c.get('finding', '').strip() or '—'} |")
    L += ["", "### Sources", ""]
    for c in reg["claims"]:
        for s in c.get("sources", []):
            L.append(f"- {c['id']}: <{s}>")
    L += ["", "## Radio parameters still illustrative", "",
          "Replace with datasheet or measured values in `forgestar/params/rf.yaml` (set `status` and `source`). "
          "Owner: RF/SDR engineer.", "", "| Link | Parameter | Value | Assumed basis |", "|---|---|---|---|"]
    L += [f"| {l} | {f} | {v} | {s} |" for l, f, v, st, s in open_rf]
    L += ["", "## Readiness items to confirm with counsel", ""]
    L += [f"- **{i['id']}** {i['title']}" for i in rd["items"] if i.get("reverify")]
    L += ["", "## Financial model", "",
          "Every group in `model/assumptions.yaml` is illustrative: "
          + ", ".join(f"`{k}`" for k in model if k != "years") + ". Owner: founder/CFO. Replace with quotes, "
          "signed LOIs and term sheets as they arrive."]
    out = ROOT / "docs/verification/VERIFY.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L[:10]))


if __name__ == "__main__":
    main()
