"""Closing the SLA gap at equatorial sites (Nairobi, Lagos): low-inclination plane vs equatorial gateways.

Baseline from sim/latency_sim.py: 36 sats at 45°, isoflux antenna (16° mask), 4 gateways (Hartebeesthoek,
Cape Town, Walvis Bay, Mauritius) meets 95% ≤ 60 min in SADC but leaves Nairobi/Lagos at ~2 h.
Options add satellites in a low-inclination plane and/or gateways near the equator.

Usage: UPLINK_MASK_DEG=16 python3 sim/equatorial_study.py   -> sim/results/equatorial.md
Costs are illustrative: satellite incl. launch+insurance ~$0.75M; owned gateway ~$0.35M capex;
leased gateway passes ~$60k/yr.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ.setdefault("UPLINK_MASK_DEG", "16")
import numpy as np  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import latency_sim as L  # noqa: E402
from forgestar.orbits import Constellation, Site  # noqa: E402

SAT_COST, GW_CAPEX, GW_LEASE = 0.75, 0.35, 0.06  # $M
EXTRA_GW = {"Malindi": Site("Malindi (Kenya)", "Africa", -3.0, 40.2),
            "Lagos": L.GW["Lagos"], "Libreville": Site("Libreville (Gabon)", "Africa", 0.4, 9.45),
            "Maputo": Site("Maputo (Mozambique)", "SADC", -25.97, 32.57)}
BASE_GW = ["Hartebeesthoek", "Cape Town", "Walvis Bay", "Mauritius"]
GWS = {**L.GW, **EXTRA_GW}

OPTIONS = [
    ("Baseline: 36 @45°, 4 gateways", [Constellation(36, 6, 45.0)], BASE_GW),
    ("+ Malindi + Lagos gateways", [Constellation(36, 6, 45.0)], BASE_GW + ["Malindi", "Lagos"]),
    ("+ 6 sats in one 10° plane", [Constellation(36, 6, 45.0), Constellation(6, 1, 10.0)], BASE_GW),
    ("+ 6 sats @10° + Malindi + Lagos", [Constellation(36, 6, 45.0), Constellation(6, 1, 10.0)], BASE_GW + ["Malindi", "Lagos"]),
    ("+ 8 sats @10° (2 planes) + Malindi + Lagos + Libreville",
     [Constellation(36, 6, 45.0), Constellation(8, 2, 10.0)], BASE_GW + ["Malindi", "Lagos", "Libreville"]),
    ("+ 6 sats @10° + Malindi + Lagos + Maputo gateways",
     [Constellation(36, 6, 45.0), Constellation(6, 1, 10.0)], BASE_GW + ["Malindi", "Lagos", "Maputo"]),
    ("42 @45° + 6 @10° + Malindi + Lagos", [Constellation(42, 7, 45.0), Constellation(6, 1, 10.0)], BASE_GW + ["Malindi", "Lagos"]),
    ("48 @45° + 6 @10° + Malindi + Lagos", [Constellation(48, 6, 45.0), Constellation(6, 1, 10.0)], BASE_GW + ["Malindi", "Lagos"]),
]


def main():
    t = np.arange(0, L.DAYS * 86400, L.STEP)
    names = [s.name.split(" (")[0] for s in L.CUSTOMERS]
    L_ = ["# Equatorial SLA study", "",
          f"p95 delivery time (min), resend-until-acked, uplink mask {L.UPLINK_MASK:.0f}° (isoflux antenna), 550 km. "
          "Extra cost vs baseline is illustrative. Generated by `sim/equatorial_study.py`.", "",
          "| Option | " + " | ".join(names) + " | Sites ≤60 min | Extra sats | Extra gateways | Extra capex ($M) |",
          "|---|" + "---|" * (len(names) + 4)]
    base_sats = 36
    for label, shells, gws in OPTIONS:
        r = L.delivery_minutes(shells, [GWS[g] for g in gws], t)
        p95 = [float(np.percentile(r[s.name], 95)) for s in L.CUSTOMERS]
        ok = sum(v <= L.SLA_MIN for v in p95)
        n = sum(sh.n for sh in shells) - base_sats
        g = len(gws) - len(BASE_GW)
        L_.append(f"| {label} | " + " | ".join(f"{'**' if v <= 60 else ''}{v:.0f}{'**' if v <= 60 else ''}" for v in p95)
                  + f" | {ok}/{len(p95)} | {n} | {g} | {n * SAT_COST + g * GW_CAPEX:.1f} |")
        print("done", label, flush=True)
    L_ += ["", f"Bold = meets 95% ≤ {L.SLA_MIN:.0f} min. Leasing a gateway instead of building one costs ~${GW_LEASE*1000:.0f}k/yr."]
    out = Path(__file__).parent / "results" / "equatorial.md"; out.write_text("\n".join(L_) + "\n")
    print("\n".join(L_))


if __name__ == "__main__":
    main()
