"""End-to-end store-and-forward delivery time: satellites vs gateways.

A message waits on the ground until a satellite is overhead (NB-IoT uplink mask from the link
budget), rides on board until that satellite passes a gateway (10° mask), then lands.
For each constellation and gateway network we report p50 / p95 delivery time at customer sites.

The question it answers: to meet a "95% within 60 minutes" SLA, is it cheaper to add
satellites (~$0.6–0.9M each incl. launch) or gateways (~$0.1–0.35M each)?

Usage: python3 sim/latency_sim.py     -> sim/results/latency.md
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from forgestar.linkbudget import LINKS  # noqa: E402
from forgestar.orbits import Constellation, Site, look, propagate_ecef  # noqa: E402

DAYS, STEP = 2.0, 30.0
import os
UPLINK_MASK = float(os.environ.get("UPLINK_MASK_DEG", LINKS["nbiot_uplink"].min_elevation(3.0)))
GW_MASK = 10.0
SLA_MIN = 60.0

CUSTOMERS = [
    Site("Johannesburg (mining)", "SA", -26.2, 28.0),
    Site("Agulhas EEZ (fisheries)", "SA", -38.0, 22.0),
    Site("Maputo corridor (FORGE Freight)", "SADC", -23.5, 35.0),
    Site("Lusaka (logistics)", "SADC", -15.4, 28.3),
    Site("Dar es Salaam (port)", "SADC", -6.8, 39.3),
    Site("Nairobi", "Africa", -1.3, 36.8),
    Site("Lagos", "Africa", 6.5, 3.4),
]
GW = {
    "Hartebeesthoek": Site("Hartebeesthoek", "SA", -25.89, 27.69),
    "Cape Town": Site("Cape Town", "SA", -33.93, 18.42),
    "Walvis Bay": Site("Walvis Bay", "SADC", -22.95, 14.5),
    "Nairobi": Site("Nairobi GW", "Africa", -1.3, 36.8),
    "Mauritius": Site("Mauritius", "SADC", -20.2, 57.5),
    "Lagos": Site("Lagos GW", "Africa", 6.5, 3.4),
    "Marion Island": Site("Marion Island", "SA", -46.9, 37.9),
}
GATEWAY_SETS = {
    "SA only (2)": ["Hartebeesthoek", "Cape Town"],
    "SA + Walvis + Mauritius (4)": ["Hartebeesthoek", "Cape Town", "Walvis Bay", "Mauritius"],
    "+ Nairobi + Marion (6)": ["Hartebeesthoek", "Cape Town", "Walvis Bay", "Mauritius", "Nairobi", "Marion Island"],
    "+ Lagos (7)": list(GW),
}
CONSTELLATIONS = [Constellation(12, 3, 45.0, label="12 sats 45°"), Constellation(24, 4, 45.0, label="24 sats 45°"),
                  Constellation(36, 6, 45.0, label="36 sats 45°"), Constellation(48, 6, 45.0, label="48 sats 45°")]


def next_true(v: np.ndarray) -> np.ndarray:
    """For a (T, N) bool array, index of the next True at or after each t (T = never)."""
    T = v.shape[0]
    out = np.full(v.shape, T, dtype=np.int64)
    nxt = np.full(v.shape[1], T, dtype=np.int64)
    for t in range(T - 1, -1, -1):
        nxt = np.where(v[t], t, nxt); out[t] = nxt
    return out


POLICY = os.environ.get("POLICY", "resend")  # resend: device re-sends each pass until acked; single: one copy


def delivery_minutes(c: Constellation, gws: list[Site], t: np.ndarray) -> dict[str, np.ndarray]:
    sat = propagate_ecef(c, t)
    el_c, _ = look(sat, CUSTOMERS)             # (T, P, N)
    el_g, _ = look(sat, gws)
    gw_vis = (el_g >= GW_MASK).any(1)          # (T, N)
    next_gw = next_true(gw_vis)
    T = len(t)
    horizon = T // 2                           # messages created in the first day; second day lets them land
    out = {}
    for j, s in enumerate(CUSTOMERS):
        up = next_true(el_c[:, j, :] >= UPLINK_MASK)          # (T, N): next pass of each satellite
        up_h = np.minimum(up[:horizon], T - 1)
        land = np.take_along_axis(next_gw, up_h, axis=0)        # gateway time for a copy given to each sat
        land = np.where(up[:horizon] >= T, T, land)
        if POLICY == "single":                                  # only the first satellite overhead carries it
            first = up[:horizon].argmin(1)
            g = land[np.arange(horizon), first]
        else:                                                   # every passing satellite gets a copy until acked
            g = land.min(1)
        out[s.name] = np.where(g >= T, np.inf, (g - np.arange(horizon)) * STEP / 60)
    return out


def fmt(x):
    return "never" if not np.isfinite(x) else (f"{x/60:.1f} h" if x >= 90 else f"{x:.0f} min")


def main():
    t = np.arange(0, DAYS * 86400, STEP)
    L = ["# End-to-end delivery time: satellites vs gateways", "",
         f"Message waits for a satellite (uplink mask {UPLINK_MASK:.0f}°), rides on board, lands at the first gateway pass "
         f"({GW_MASK:.0f}°). Policy: **{POLICY}** (resend = device re-sends on each pass until the ground acks; "
         "single = one copy on the first satellite). 550 km, J2, {DAYS:g} days. Worst customer site shown; SLA target: 95% within {SLA_MIN:.0f} min. "
         "Generated by `sim/latency_sim.py`; illustrative.", "",
         "| Constellation | Gateways | Worst-site p50 | Worst-site p95 | Worst site | Sites meeting SLA |",
         "|---|---|---|---|---|---|"]
    grid = {}
    for c in CONSTELLATIONS:
        for gname, gl in GATEWAY_SETS.items():
            res = delivery_minutes(c, [GW[g] for g in gl], t)
            p95 = {k: float(np.percentile(v, 95)) for k, v in res.items()}
            p50 = {k: float(np.percentile(v, 50)) for k, v in res.items()}
            worst = max(p95, key=p95.get)
            ok = sum(v <= SLA_MIN for v in p95.values())
            grid[(c.label, gname)] = (p95[worst], ok, p95)
            L.append(f"| {c.label} | {gname} | {fmt(p50[worst])} | **{fmt(p95[worst])}** | {worst} | {ok}/{len(CUSTOMERS)} |")
        print(f"done {c.label}", flush=True)
    base = grid[("24 sats 45°", "SA only (2)")][2]
    L += ["", "## Per site, 24 satellites", "", "| Site | SA gateways only | 6 gateways | 7 gateways |", "|---|---|---|---|"]
    for s in CUSTOMERS:
        L.append(f"| {s.name} | {fmt(base[s.name])} | {fmt(grid[('24 sats 45°', '+ Nairobi + Marion (6)')][2][s.name])} | "
                 f"{fmt(grid[('24 sats 45°', '+ Lagos (7)')][2][s.name])} |")
    L += ["", "p95 delivery time. Gateways can be leased passes (e.g. KSAT/Leaf Space-style networks) or partner SatNOGS-class "
          "stations, as long as data is relayed to the SA platform."]
    tag = ("" if "UPLINK_MASK_DEG" not in os.environ else f"_mask{UPLINK_MASK:.0f}") + ("" if POLICY == "resend" else "_single")
    out = Path(__file__).parent / "results" / f"latency{tag}.md"; out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
