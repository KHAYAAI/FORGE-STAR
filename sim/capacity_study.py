"""Per-pass capacity: how many messages a day can the busiest region send?

Devices are not spread evenly. Most early customers sit in southern Africa, inside one satellite
footprint. The limit is the satellites over that region, not the whole fleet.

Usage: python3 sim/capacity_study.py   -> sim/results/capacity.md
"""
from __future__ import annotations

import sys
from dataclasses import replace
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from forgestar.capacity import Capacity  # noqa: E402
from forgestar.orbits import Constellation, Site, look, propagate_ecef  # noqa: E402

BUSY = Site("Johannesburg", "SA", -26.2, 28.0)
DEVICES = {"Year 3 (40k devices)": 40_000, "Year 4 (110k)": 110_000, "Year 6 (330k)": 330_000}
BUSY_SHARE = 0.6    # share of all devices inside the busiest footprint (southern Africa) at once
FLEETS = [("Stage 2: 12 sats at 45°", [Constellation(12, 3, 45.0)]),
          ("Stage 3: 42 at 45° + 6 at 10°", [Constellation(42, 7, 45.0), Constellation(6, 1, 10.0)]),
          ("Stage 4: 120 at 45° + 30 at 10°", [Constellation(120, 12, 45.0), Constellation(30, 3, 10.0)])]
MASK = 16.0


def mean_in_view(shells, mask=MASK, days=2.0, step=60.0) -> float:
    t = np.arange(0, days * 86400, step)
    sat = np.concatenate([propagate_ecef(c, t) for c in shells], axis=1)
    el, _ = look(sat, [BUSY])
    return float((el[:, 0, :] >= mask).sum(-1).mean())


def main():
    base = Capacity()
    cases = [("NB-IoT, 1 carrier (8 W isoflux payload)", base),
             ("NB-IoT, 1 carrier, deep coverage mode", replace(base, deep_coverage_factor=4.0)),
             ("NB-IoT, 4 carriers (phased array, Stage 4 payload)", replace(base, carriers=4)),
             ("Compact own protocol, 1 carrier (20-byte overhead)", replace(base, overhead_bytes=20))]
    L = ["# Per-pass capacity (illustrative)", "",
         f"One NB-IoT carrier has {base.uplink_tones} uplink tones. A {base.payload_bytes}-byte message with "
         f"{base.overhead_bytes} bytes of NB-IoT signalling takes about {base.seconds_per_message:.1f} s of one tone at "
         f"{base.tone_rate_bps:.0f} bit/s. With {base.access_efficiency:.0%} of tone-time carrying messages, one satellite "
         f"takes about **{base.messages_per_second:.1f} messages a second** per carrier.", "",
         f"The busiest region is southern Africa: {BUSY_SHARE:.0%} of all devices are assumed to sit inside one footprint. "
         f"Satellites in view are counted over Johannesburg at a {MASK:.0f}° mask. Generated by `sim/capacity_study.py`.", "",
         "## Satellites over the busy region", "", "| Fleet | Average satellites in view | Messages a day, 1 carrier |", "|---|---|---|"]
    views = {}
    for name, shells in FLEETS:
        v = mean_in_view(shells); views[name] = v
        L.append(f"| {name} | {v:.2f} | {base.messages_per_day(v):,.0f} |")
    L += ["", "## Messages per device per day the busy region can send", "",
          "| Payload and protocol | Fleet | " + " | ".join(DEVICES) + " |", "|---|---|" + "---|" * len(DEVICES)]
    for cname, cap in cases:
        for fname, _ in FLEETS[1:]:
            row = [f"{cap.per_device_per_day(n * BUSY_SHARE, views[fname]):.1f}" for n in DEVICES.values()]
            L.append(f"| {cname} | {fname.split(':')[0]} | " + " | ".join(row) + " |")
    s3 = views[FLEETS[1][0]]
    L += ["", "## What this means", "",
          f"- **Stage 3 with one carrier supports about {base.per_device_per_day(330_000 * BUSY_SHARE, s3):.1f} messages per device per day "
          "at 330,000 devices.** Hourly reporting for every device does not fit. A few readings a day does.",
          "- **Capacity, not coverage, is the tighter limit at scale.** Passes come every few tens of minutes; the queue on each pass is the constraint.",
          "- **Deep coverage mode costs capacity.** It lowers the elevation mask but divides throughput by about four. Use it for hard-to-reach devices only.",
          "- **The levers:** a compact store-and-forward protocol (less signalling per message), more carriers (needs more downlink power or a multi-beam array), "
          "more satellites over the busy region, and pricing tiers that sell hourly reporting as a premium.",
          "- **The financial model should cap messages per device** by stage. A device plan of 2 to 4 messages a day fits Stage 3; hourly plans need Stage 4 or the compact protocol.",
          "", "*First-order. Rates, signalling overhead and access efficiency must come from the lab test-bed.*"]
    out = Path(__file__).parent / "results" / "capacity.md"; out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
