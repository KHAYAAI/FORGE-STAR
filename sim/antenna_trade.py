"""Payload antenna trade study: which S-band antenna closes NB-IoT both ways at a useful elevation?

For each option the same aperture serves uplink (receive) and downlink (transmit).
The usable elevation mask is the higher of the two. We then run 24 sats at 45°
over South Africa to show what that mask does to service.

All parameters are illustrative (mass, power, cost, gain). Replace with vendor quotes.
Usage: python3 sim/antenna_trade.py
"""
from __future__ import annotations

import sys
from dataclasses import replace
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from forgestar.linkbudget import LINKS  # noqa: E402
from forgestar.orbits import Constellation, Site, look, propagate_ecef  # noqa: E402

UP, DOWN = LINKS["nbiot_uplink"], LINKS["nbiot_downlink"]

# name, antenna changes, downlink RF power (dBW), DC power (W), mass (kg), est. cost ($k), note
OPTIONS = [
    ("A. Patch 14 dBi, ±30° beam, 2 W (baseline)", dict(sat_pattern="cos", sat_half_beam_deg=30.0), {}, 3.0, 12, 0.4, 15,
     "Simple, cheap. Narrow footprint."),
    ("B. Patch 14 dBi, 10 W PA", dict(sat_pattern="cos", sat_half_beam_deg=30.0), {}, 10.0, 45, 0.7, 40,
     "Brute force. DC power and thermal hard on 6U."),
    ("C. Isoflux 5 dBi peak at 20°, 2 W", dict(sat_pattern="isoflux", edge_el_deg=20.0), {"g": 5.0}, 3.0, 12, 0.5, 35,
     "Shaped beam cancels range loss. Even footprint."),
    ("D. Isoflux 5 dBi peak at 20°, 5 W", dict(sat_pattern="isoflux", edge_el_deg=20.0), {"g": 5.0}, 7.0, 25, 0.6, 45,
     "Isoflux with margin."),
    ("D2. Isoflux 7 dBi peak at 30°, 5 W", dict(sat_pattern="isoflux", edge_el_deg=30.0), {"g": 7.0}, 7.0, 25, 0.6, 45,
     "Narrower shaped cone: more gain, smaller footprint."),
    ("D3. Isoflux 5 dBi peak at 20°, 8 W", dict(sat_pattern="isoflux", edge_el_deg=20.0), {"g": 5.0}, 9.0, 38, 0.7, 55,
     "Wide shaped beam, enough power to close."),
    ("E. 4×4 phased array 17 dBi, 4 W total", dict(sat_pattern="array", max_scan_deg=60.0), {"g": 17.0}, 6.0, 30, 1.2, 150,
     "Steers to users; most capacity. Highest cost/risk."),
    ("F. Baseline + deeper coverage enhancement", dict(sat_pattern="cos", sat_half_beam_deg=30.0), {"req_dl": -12.0, "req_ul": -12.0}, 3.0, 12, 0.4, 15,
     "More NB-IoT repetitions: ~4× less throughput per device."),
]

SA_SITES = [Site("Johannesburg", "SA", -26.2, 28.0), Site("Cape Town", "SA", -33.9, 18.4),
            Site("Agulhas EEZ", "SA", -38.0, 22.0), Site("Marion Island EEZ", "SA", -46.9, 37.7)]


def mask_for(opt):
    _, ant, extra, dl_dbw, *_ = opt
    g = extra.get("g")
    up = replace(UP, **ant, **({"rx_gain_dbi": g} if g else {}),
                 **({"required_snr_db": extra["req_ul"]} if "req_ul" in extra else {}))
    dn = replace(DOWN, **ant, tx_power_dbw=dl_dbw, **({"tx_gain_dbi": g} if g else {}),
                 **({"required_snr_db": extra["req_dl"]} if "req_dl" in extra else {}))
    mu, md = up.min_elevation(3.0), dn.min_elevation(3.0)
    return mu, md, (None if mu is None or md is None else max(mu, md)), up, dn


def sa_service(mask, days=2.0, step=30.0):
    t = np.arange(0, days * 86400, step)
    el, _ = look(propagate_ecef(Constellation(24, 4, 45.0), t), SA_SITES)
    vis = (el >= mask).any(-1)
    worst_mean, worst_max = 0.0, 0.0
    for j in range(vis.shape[1]):
        g, run = [], 0
        for v in vis[:, j]:
            if v:
                if run: g.append(run * step)
                run = 0
            else:
                run += 1
        if run: g.append(run * step)
        worst_mean = max(worst_mean, np.mean(g) if g else 0); worst_max = max(worst_max, max(g) if g else 0)
    return worst_mean / 60, worst_max / 60, 100 * vis.mean(0).min()


def fmt(m):
    return f"{m/60:.1f} h" if m >= 90 else f"{m:.0f} min"


def main():
    L = ["# Payload antenna trade study (illustrative)", "",
         "Same S-band aperture for NB-IoT uplink and downlink, 550 km. Service column: 24 satellites at 45°, "
         "worst South African site (incl. EEZ). Generated by `sim/antenna_trade.py`.", "",
         "| Option | Uplink from | Downlink from | Usable mask | SA typical wait | SA longest wait | DC power | Mass | Est. cost | Note |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for opt in OPTIONS:
        name, _, _, _, dc, kg, cost, note = opt
        mu, md, mask, *_ = mask_for(opt)
        el = lambda x: "never" if x is None else f"{x:.0f}°"
        if mask is None:
            _, _, _, up, dn = mask_for(opt)
            best_dl = max(dn.margin_db(e) for e in range(5, 91))
            L.append(f"| {name} | {el(mu)} | never (best {best_dl:+.1f} dB) | **no** | — | — | {dc} W | {kg} kg | ${cost}k | {note} |"); continue
        mean, mx, cov = sa_service(mask)
        L.append(f"| {name} | {el(mu)} | {el(md)} | **{mask:.0f}°** | {fmt(mean)} | {fmt(mx)} | {dc} W | {kg} kg | ${cost}k | {note} |")
    L += ["", "**Recommendation (illustrative):** fly the demonstrator with the simple patch plus deeper coverage "
          "enhancement (F, software only), so devices can attach from ~26°. Design the Stage 2 payload around a shaped "
          "isoflux antenna (D2/D3), which gives the lowest mask for its cost if the bus can supply ~25–40 W during passes. "
          "Keep the phased array (E) for Stage 4.", "",
          "Reading the table:",
          "- The baseline patch is limited by the **downlink**: devices hear nothing below ~37°, so they can't attach.",
          "- Raising power alone (B) helps, but costs DC power and heat a 6U can't easily spare.",
          "- A **shaped isoflux beam** (C/D) gives the same margin at every elevation, but a wide beam has little gain. "
          "At 2–5 W it sits just below the 3 dB target. It closes with a narrower cone (D2) or ~8 W (D3).",
          "- A phased array (E) gives the most capacity but is the Stage 4+ option, not the demonstrator.",
          "- Deeper repetition (F) is a software lever. It works but cuts throughput per device.",
          "", "*Illustrative. Replace gains, powers, masses and costs with vendor data before decisions.*"]
    out = Path(__file__).parent / "results" / "antenna_trade.md"; out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
