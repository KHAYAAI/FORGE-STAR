"""Reference positions/elevations from forgestar.orbits for the C pass predictor test."""
import math, sys
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parents[3]; sys.path.insert(0, str(ROOT))
from forgestar.orbits import Constellation, Site, look, propagate_ecef  # noqa: E402
c = Constellation(1, 1, 45.0, alt_km=550.0)
t = np.array([0.0, 600.0, 3600.0, 86400.0, 3 * 86400.0])
p = propagate_ecef(c, t)[:, 0, :]
el, _ = look(propagate_ecef(c, t), [Site("H", "SA", -25.89, 27.69)])
lines = ["/* Generated by make_orbit_vectors.py from forgestar/orbits.py. */",
         f"#define OV_N {len(t)}",
         "static const double OV_T[OV_N] = {" + ", ".join(f"{x:.1f}" for x in t) + "};",
         "static const double OV_POS[OV_N][3] = {" + ", ".join("{%.9f, %.9f, %.9f}" % tuple(r) for r in p) + "};",
         "static const double OV_EL_DEG[OV_N] = {" + ", ".join(f"{x:.9f}" for x in el[:, 0, 0]) + "};"]
(Path(__file__).parent / "orbit_vectors.h").write_text("\n".join(lines) + "\n")
print("ok")
