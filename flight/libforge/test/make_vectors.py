"""Generate test/vectors.h from the Python ground implementation (the reference).

The C tests must reproduce these bytes exactly. Re-run after changing frames.py or fec.py:
    python3 flight/libforge/test/make_vectors.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from forgestar.fec import encode_block  # noqa: E402
from forgestar import conv  # noqa: E402
import numpy as np  # noqa: E402
from forgestar.frames import Ack, Frame, Record, short_id  # noqa: E402

recs = [
    Record(short_id("pump-0000"), 1790000000, -24.12345, 29.54321, {"flow_lpm": 120.5, "running": True}),
    Record(short_id("vessel-0003"), 1790000060, -34.5, 18.25, {"mmsi": 601000003, "sog_kn": 7.1}),
    Record(short_id("collar-0002"), 1790000123, -24.98765, 31.6, {"battery_v": 3.71}),
]
frame = Frame(7, 42, 1790000999, recs).encode()
link = encode_block(frame)


def carr(name, b):
    body = ",".join(f"0x{x:02x}" for x in b)
    return f"static const uint8_t {name}[{len(b)}] = {{{body}}};\n"


out = ["/* Generated by make_vectors.py from forgestar/frames.py + fec.py. Do not edit. */",
       "#include <stdint.h>", f"#define VEC_NREC {len(recs)}", "#define VEC_SAT 7", "#define VEC_SEQ 42u",
       "#define VEC_TDL 1790000999u",
       'static const char *VEC_NAMES[VEC_NREC] = {"pump-0000", "vessel-0003", "collar-0002"};']
out.append("static const struct { uint32_t sid, t; int32_t lat, lon; const char *payload; } VEC_RECS[VEC_NREC] = {")
for r in recs:
    pj = json.dumps(r.payload, separators=(",", ":")).replace('"', '\\"')
    out.append(f'  {{{r.device_short_id}u, {r.t_created}u, {round(r.lat*1e5)}, {round(r.lon*1e5)}, "{pj}"}},')
out.append("};")
out.append(carr("VEC_FRAME", frame) + carr("VEC_LINK", link))
ack = Ack(4, 9, 1790001000, [(recs[0].device_short_id, recs[0].t_created), (recs[2].device_short_id, recs[2].t_created)]).encode()
out.append(carr("VEC_ACK", ack))
out.append(carr("VEC_CONV", np.packbits(conv.encode(link)).tobytes()))
(Path(__file__).parent / "vectors.h").write_text("\n".join(out))
print(f"frame {len(frame)} bytes, link block {len(link)} bytes")
