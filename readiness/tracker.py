"""FORGE STAR readiness tracker.

Reads readiness/readiness.yaml and writes readiness/STATUS.md with:
  * the critical path to early service (longest dependency chain)
  * items that are late, starting soon, or blocked
  * a Mermaid Gantt chart (GitHub renders it)
  * every item that needs regulatory re-verification

Usage: python3 readiness/tracker.py [--today YYYY-MM-DD]
"""
from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path

import yaml

HERE = Path(__file__).parent


def add_months(d: dt.date, m: float) -> dt.date:
    whole = int(m); days = int(round((m - whole) * 30.4))
    y, mo = divmod(d.month - 1 + whole, 12)
    return dt.date(d.year + y, mo + 1, min(d.day, 28)) + dt.timedelta(days=days)


def schedule(items: list[dict]) -> dict[str, dict]:
    """Earliest start = max(planned start, latest dependency finish). Raises on cycles or unknown ids."""
    by = {i["id"]: i for i in items}
    for i in items:
        for d in i.get("depends", []):
            if d not in by:
                raise ValueError(f"{i['id']} depends on unknown item {d}")
    out, state = {}, {}

    def visit(k, stack):
        if state.get(k) == "done":
            return out[k]
        if state.get(k) == "visiting":
            raise ValueError("dependency cycle: " + " -> ".join(stack + [k]))
        state[k] = "visiting"
        it = by[k]
        dep_end, crit = 0.0, None
        for d in it.get("depends", []):
            r = visit(d, stack + [k])
            if r["end"] > dep_end:
                dep_end, crit = r["end"], d
        s = max(float(it["start"]), dep_end)
        out[k] = {"start": s, "end": s + float(it["months"]), "driver": crit, "slip": s - float(it["start"])}
        state[k] = "done"
        return out[k]

    for k in by:
        visit(k, [])
    return out


def apply(items: list[dict], overrides: dict) -> list[dict]:
    import copy
    out = copy.deepcopy(items); by = {i["id"]: i for i in out}
    for k, v in overrides.items():
        if k.startswith("_"): continue
        if k not in by: raise ValueError(f"scenario overrides unknown item {k}")
        by[k].update(v)
    return out


def critical_path(sched: dict, target: str) -> list[str]:
    path, k = [], target
    while k:
        path.append(k); k = sched[k]["driver"]
    return path[::-1]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--today"); ap.add_argument("--target", default="V1")
    a = ap.parse_args()
    cfg = yaml.safe_load((HERE / "readiness.yaml").read_text())
    start = cfg["start"] if isinstance(cfg["start"], dt.date) else dt.date.fromisoformat(cfg["start"])
    today = dt.date.fromisoformat(a.today) if a.today else (cfg.get("today") if isinstance(cfg.get("today"), dt.date) else dt.date.today())
    items = cfg["items"]; by = {i["id"]: i for i in items}
    sched = schedule(items)
    now_m = (today - start).days / 30.4
    cp = critical_path(sched, a.target)

    def date(m): return add_months(start, m).isoformat()

    late = [i for i in items if i["status"] != "done" and sched[i["id"]]["end"] < now_m]
    should_run = [i for i in items if i["status"] == "todo" and sched[i["id"]]["start"] <= now_m < sched[i["id"]]["end"]]
    soon = [i for i in items if i["status"] == "todo" and now_m <= sched[i["id"]]["start"] < now_m + 3]
    blocked = [i for i in items if i["status"] == "blocked"]
    slipped = [i for i in items if sched[i["id"]]["slip"] > 0.5]
    done = sum(i["status"] == "done" for i in items)

    L = ["# FORGE STAR readiness status", "",
         f"Generated by `readiness/tracker.py` on {today.isoformat()} from `readiness/readiness.yaml`. "
         f"Plan start {start.isoformat()}. {done}/{len(items)} items done.", "",
         f"## Critical path to {by[a.target]['title']}", "",
         f"Earliest finish: **{date(sched[a.target]['end'])}** (month {sched[a.target]['end']:.0f}).", "",
         "| # | Item | Starts | Ends | Status |", "|---|---|---|---|---|"]
    L += [f"| {k} | {by[k]['title']} | {date(sched[k]['start'])} | {date(sched[k]['end'])} | {by[k]['status']} |" for k in cp]

    if cfg.get("scenarios"):
        L += ["", "## Plan options", "", "| Option | Stage 2 finishes | Months | Critical path |", "|---|---|---|---|",
              f"| As planned | {date(sched[a.target]['end'])} | {sched[a.target]['end']:.0f} | {' → '.join(cp)} |"]
        for name, ov in cfg["scenarios"].items():
            sc = schedule(apply(items, ov))
            L.append(f"| {ov.get('_label', name)} (`{name}`) | {date(sc[a.target]['end'])} | {sc[a.target]['end']:.0f} | "
                     f"{' → '.join(critical_path(sc, a.target))} |")

    def section(title, rows, empty):
        L.extend(["", f"## {title}", ""])
        if not rows:
            L.append(empty); return
        L.extend(["| # | Item | Window | Owner | Status |", "|---|---|---|---|---|"])
        L.extend(f"| {i['id']} | {i['title']} | {date(sched[i['id']]['start'])} → {date(sched[i['id']]['end'])} | {i.get('owner', 'TBD')} | {i['status']} |" for i in rows)

    section("Late (should have finished)", late, "Nothing late.")
    section("Should be under way now but marked todo", should_run, "Nothing.")
    section("Starting in the next 3 months", soon, "Nothing.")
    section("Blocked", blocked, "Nothing blocked.")
    if slipped:
        L += ["", "## Pushed later by dependencies", "", "| # | Planned start | Earliest start | Waiting on |", "|---|---|---|---|"]
        L += [f"| {i['id']} | month {i['start']} | month {sched[i['id']]['start']:.0f} | {sched[i['id']]['driver']} |" for i in slipped]
    unowned = [i["id"] for i in items if i.get("owner", "TBD") == "TBD" and i["status"] != "done"]
    if unowned:
        L += ["", f"**No owner yet:** {', '.join(unowned)}."]

    L += ["", "## Gantt", "", "```mermaid", "gantt", "  dateFormat YYYY-MM-DD", "  axisFormat %b %y"]
    for ws, name in cfg["workstreams"].items():
        L.append(f"  section {name}")
        for i in items:
            if i["ws"] != ws: continue
            tag = {"done": "done, ", "doing": "active, ", "blocked": "crit, "}.get(i["status"], "")
            if i["id"] in cp and tag == "": tag = "crit, "
            label = i["title"].split(" (")[0].split(";")[0].replace(":", " -")[:48]
            days = int(i["months"] * 30.4)
            L.append(f"  {label} :{tag}{i['id']}, {date(sched[i['id']]['start'])}, {days}d")
    L += ["```", "", "## To re-verify with counsel before external use", ""]
    L += [f"- **{i['id']}** {i['title']}" + (f" — {i['note']}" if i.get("note") else "") for i in items if i.get("reverify")]
    (HERE / "STATUS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:14 + len(cp)]))


if __name__ == "__main__":
    main()
